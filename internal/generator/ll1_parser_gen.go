package generator

import (
	"bytes"
	"fmt"
	"os"
	"text/template"

	"genanalex/internal/yapar"
)

type ll1CellData struct {
	Terminal     string
	ProductionID int
}

type ll1RowData struct {
	Head  string
	Cells []ll1CellData
}

type ll1TemplateData struct {
	parserTemplateData
	Terminals []string
	Rows      []ll1RowData
}

// GenerateLL1ParserSource emits a predictive parser from an existing LL1 table.
// Table construction and grammar validation remain owned by the yapar package.
func GenerateLL1ParserSource(outputPath string, g *yapar.Grammar, table *yapar.LL1Table) error {
	if g == nil {
		return fmt.Errorf("generating LL1 parser source: grammar is required")
	}
	if table == nil {
		return fmt.Errorf("generating LL1 parser source: parsing table is required")
	}
	data := ll1TemplateData{parserTemplateData: buildParserGrammarData(g), Terminals: sortedBoolKeys(g.Terminals)}
	for _, head := range sortedBoolKeys(g.NonTerminals) {
		row := ll1RowData{Head: head}
		for _, terminal := range data.Terminals {
			if id, ok := table.M[head][terminal]; ok {
				row.Cells = append(row.Cells, ll1CellData{Terminal: terminal, ProductionID: id})
			}
		}
		data.Rows = append(data.Rows, row)
	}
	tmpl, err := template.New("ll1-parser").Parse(ll1ParserTemplate)
	if err != nil {
		return fmt.Errorf("parsing LL1 parser template: %w", err)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return fmt.Errorf("executing LL1 parser template: %w", err)
	}
	if err := os.WriteFile(outputPath, buf.Bytes(), 0o644); err != nil {
		return fmt.Errorf("writing generated LL1 parser: %w", err)
	}
	return nil
}

