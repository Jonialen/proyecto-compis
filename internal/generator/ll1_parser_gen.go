func loadTokens(path string) ([]Token, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var tokens []Token
	if err := json.Unmarshal(data, &tokens); err != nil {
		return nil, err
	}
	return tokens, nil
}

func parseTokens(tokens []Token) error {
	endLine := 1
	for _, token := range tokens {
		if token.Line > 0 {
			endLine = token.Line
		}
	}
	stream := make([]Token, 0, len(tokens)+1)
	for _, token := range tokens {
		if token.Type == "$" {
			line := token.Line
			if line <= 0 {
				line = endLine
			}
			return fmt.Errorf("yapar: token type %q is reserved for end of input at line %d", "$", line)
		}
		if !ignoreSet[token.Type] {
			stream = append(stream, token)
		}
	}
	stream = append(stream, Token{Type: "$", Line: endLine})
	stack := []string{"$", startSymbol}
	index := 0
	for len(stack) > 0 {
		top := stack[len(stack)-1]
		lookahead := stream[index]
		if top == "$" {
			if lookahead.Type == "$" {
				return nil
			}
			return syntaxError(lookahead, endLine, []string{"$"})
		}
		if terminals[top] {
			if top != lookahead.Type {
				return syntaxError(lookahead, endLine, []string{top})
			}
			stack = stack[:len(stack)-1]
			index++
			continue
		}
		row := predictiveTable[top]
		id, ok := row[lookahead.Type]
		if !ok {
			expected := make([]string, 0, len(row))
			for terminal := range row {
				expected = append(expected, terminal)
			}
			sort.Strings(expected)
			return syntaxError(lookahead, endLine, expected)
		}
		body, ok := productions[id]
		if !ok {
			return fmt.Errorf("yapar: unknown production id %d", id)
		}
		stack = stack[:len(stack)-1]
		for i := len(body)-1; i >= 0; i-- {
			stack = append(stack, body[i])
		}
	}
	return syntaxError(stream[index], endLine, nil)
}

func syntaxError(token Token, endLine int, expected []string) error {
	line := token.Line
	if line <= 0 {
		line = endLine
	}
	if len(expected) == 0 {
		return fmt.Errorf("syntax error at line %d: got %q (%q)", line, token.Type, token.Lexeme)
	}
	return fmt.Errorf("syntax error at line %d: got %q (%q), expected %v", line, token.Type, token.Lexeme, expected)
}
